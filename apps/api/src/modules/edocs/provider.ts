/**
 * V1 default: nothing leaves the building. Documents are prepared, queued and
 * visible, and the screen says plainly that no integrator is connected. This is
 * a deliberate honest stub, not a pretend success.
 */
export class NullProvider implements EInvoiceProvider {
  readonly name = 'null';
  readonly configured = false;

  private queued(payload: EDocumentPayload): SendResult {
    return {
      ok: false,
      providerId: null,
      status: 'ERROR',
      code: 'NO_PROVIDER',
      message: `Entegratör tanımlı değil: ${payload.number} kuyrukta bekliyor. Ayarlardan sağlayıcı bağlanınca gönderilecek.`,
    };
  }

  async sendInvoice(payload: EDocumentPayload): Promise<SendResult> {
    return this.queued(payload);
  }

  async sendDespatch(payload: EDocumentPayload): Promise<SendResult> {
    return this.queued(payload);
  }

  async queryStatus(): Promise<StatusResult> {
    return { status: 'QUEUED', code: 'NO_PROVIDER', message: 'Entegratör tanımlı değil.' };
  }

  async getIncoming(): Promise<IncomingDocument[]> {
    return [];
  }
}

/**
 * Skeleton for a real integrator (Foriba/Uyumsoft/Nesbilgi style REST). Reads
 * its endpoint and credentials from the environment; the request/response
 * mapping is the only thing a new integrator changes.
 */
export class HttpProviderAdapter implements EInvoiceProvider {
  readonly name: string;

  constructor(
    private readonly opts: {
      name?: string;
      baseUrl?: string;
      username?: string;
      password?: string;
      timeoutMs?: number;
    } = {},
  ) {
    this.name = opts.name ?? process.env.EDOC_PROVIDER ?? 'http';
  }

  get configured() {
    return !!(this.opts.baseUrl ?? process.env.EDOC_BASE_URL);
  }

  private get baseUrl() {
    return this.opts.baseUrl ?? process.env.EDOC_BASE_URL ?? '';
  }

  private headers(): Record<string, string> {
    const user = this.opts.username ?? process.env.EDOC_USER ?? '';
    const pass = this.opts.password ?? process.env.EDOC_PASS ?? '';
    const headers: Record<string, string> = { 'content-type': 'application/json' };
    if (user) headers.authorization = `Basic ${Buffer.from(`${user}:${pass}`).toString('base64')}`;
    return headers;
  }

  private async call<T>(path: string, init: RequestInit = {}): Promise<T> {
    if (!this.configured) throw new Error('Entegratör adresi tanımlı değil (EDOC_BASE_URL).');
    const res = await fetch(`${this.baseUrl}${path}`, {
      ...init,
      headers: { ...this.headers(), ...(init.headers as Record<string, string>) },
      signal: AbortSignal.timeout(this.opts.timeoutMs ?? 30_000),
    });
    const text = await res.text();
    const body = text ? (JSON.parse(text) as T) : ({} as T);
    if (!res.ok) throw new Error(`${res.status}: ${text.slice(0, 200)}`);
    return body;
  }

  private async send(path: string, payload: EDocumentPayload): Promise<SendResult> {
    try {
      const body = await this.call<{ id?: string; code?: string; message?: string }>(path, {
        method: 'POST',
        body: JSON.stringify(payload),
      });
      return {
        ok: true,
        providerId: body.id ?? null,
        status: 'SENT',
        code: body.code ?? '1000',
        message: explainGib(body.code ?? '1000', body.message ?? 'Gönderildi.'),
      };
    } catch (e) {
      const message = (e as Error).message;
      return { ok: false, status: 'ERROR', code: message.includes('abort') ? 'TIMEOUT' : null, message: explainGib(null, message) };
    }
  }

  sendInvoice(payload: EDocumentPayload) {
    return this.send('/invoices', payload);
  }

  sendDespatch(payload: EDocumentPayload) {
    return this.send('/despatches', payload);
  }

  async queryStatus(ettn: string): Promise<StatusResult> {
    try {
      const body = await this.call<{ status?: string; code?: string; message?: string }>(`/documents/${ettn}/status`);
      const status = (body.status ?? 'SENT').toUpperCase() as StatusResult['status'];
      return { status, code: body.code ?? null, message: explainGib(body.code, body.message ?? 'Durum alındı.') };
    } catch (e) {
      return { status: 'ERROR', code: null, message: (e as Error).message };
    }
  }

  async getIncoming(since?: Date): Promise<IncomingDocument[]> {
    try {
      const q = since ? `?since=${since.toISOString()}` : '';
      const body = await this.call<{ items?: IncomingDocument[] }>(`/incoming${q}`);
      return body.items ?? [];
    } catch {
      return [];
    }
  }
}

/** DI token for an injected provider; unset means "build one from the env". */
export const EDOC_PROVIDER = 'EDOC_PROVIDER';

/** Picks the adapter from the environment; NullProvider is the V1 default. */
export function createProvider(): EInvoiceProvider {
  return process.env.EDOC_BASE_URL ? new HttpProviderAdapter() : new NullProvider();
}
