/**
 * e-Document provider contract (P09).
 *
 * Cora never holds the fiscal seal: signing and filing with the revenue
 * administration stay at the integrator. Cora owns the payload, the queue and
 * the answer. Swapping integrator means writing one adapter against this
 * interface; nothing else in the app changes.
 */

export type EDocumentKind = 'E_INVOICE' | 'E_ARCHIVE' | 'E_DESPATCH';

export interface EDocumentParty {
  name: string;
  taxNumber?: string | null;
  taxOffice?: string | null;
  address?: string | null;
  district?: string | null;
  city?: string | null;
  country?: string;
  email?: string | null;
  phone?: string | null;
}

export interface EDocumentLine {
  lineNo: number;
  code: string;
  name: string;
  qty: string;
  unitCode: string;
  unitPrice?: string;
  vatRate?: string;
  lineTotal?: string;
}

/** UBL-TR shaped payload; the adapter turns it into the integrator's format. */
export interface EDocumentPayload {
  kind: EDocumentKind;
  /** cbc:UUID (ETTN) — generated by Cora so a retry cannot file twice. */
  ettn: string;
  number: string;
  issueDate: string;
  issueTime?: string;
  profileId: string;
  typeCode: string;
  currency: string;
  supplier: EDocumentParty;
  customer: EDocumentParty;
  lines: EDocumentLine[];
  /** Delivery note specifics (e-despatch). */
  despatch?: {
    actualDespatchDate?: string | null;
    carrierName?: string | null;
    carrierVkn?: string | null;
    driverName?: string | null;
    driverTckn?: string | null;
    vehiclePlate?: string | null;
    trailerPlate?: string | null;
    packageCount?: number;
    grossWeightKg?: string | null;
  };
  /** Invoice specifics. */
  totals?: {
    subtotal: string;
    discountTotal: string;
    vatTotal: string;
    grandTotal: string;
  };
  notes?: string | null;
}

export interface SendResult {
  ok: boolean;
  /** Integrator-side id, when it gave one. */
  providerId?: string | null;
  status: 'SENT' | 'ACCEPTED' | 'REJECTED' | 'ERROR';
  code?: string | null;
  message: string;
}

export interface StatusResult {
  status: 'QUEUED' | 'SENDING' | 'SENT' | 'ACCEPTED' | 'REJECTED' | 'CANCELLED' | 'ERROR';
  code?: string | null;
  message: string;
}

export interface IncomingDocument {
  ettn: string;
  number: string;
  issueDate: string;
  senderName: string;
  senderTaxNumber?: string | null;
  grandTotal?: string | null;
  kind: EDocumentKind;
}

export interface EInvoiceProvider {
  readonly name: string;
  /** Whether the provider is wired up; a NullProvider says false. */
  readonly configured: boolean;
  sendInvoice(payload: EDocumentPayload): Promise<SendResult>;
  sendDespatch(payload: EDocumentPayload): Promise<SendResult>;
  queryStatus(ettn: string): Promise<StatusResult>;
  getIncoming(since?: Date): Promise<IncomingDocument[]>;
}

